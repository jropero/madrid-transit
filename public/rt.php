<?php
// Whitelist proxy for upstreams that send no CORS headers; no other URL is reachable.
//   ?f=trip_updates|trip_updates_LD|alerts  Renfe GTFS-RT JSON (LD = Media/Larga Distancia), cached 15 s.
//   ?f=crtm&stop=8_16578    CRTM stop times (undocumented website endpoint, may change or
//                           break), cached 30 s per stop. `stop` must match ^(4|6|8|10)_\d{1,6}$.
//   ?f=emt&stop=72          EMT Madrid MobilityLabs bus arrivals (needs ../../emt.json, outside the
//                           webroot, written by the deploy workflow), cached 30 s per stop. `stop`
//                           must match ^\d{1,6}$. The credentials and the access token are never
//                           output or logged.
// Stale-while-revalidate: a copy past its TTL but under STALE_MAX s old is served at once
// (X-Data-Age tells its age) and refreshed after the response is flushed; see serve_swr().
// Abuse limits (all state lives in state_dir(), outside the webroot):
//   - `stop` must be in rt-stops.php (generated by the build); unknown -> 404, no upstream call.
//   - Upstream budget per minute (EMT_BUDGET / CRTM_BUDGET below); over it -> stale cache or 503.
//   - A failed stop is remembered NEG_TTL s (negative cache) so retries do not hit the upstream.
//   - Per client: IP_LIMIT requests/min (only a SHA-256 of IP+minute is stored) -> 429.

header('X-Content-Type-Options: nosniff');

const EMT_BUDGET = 30;  // EMT upstream calls per minute (quota is 25k/day)
const CRTM_BUDGET = 30; // CRTM upstream calls per minute
const IP_LIMIT = 120;   // requests per client per minute
const NEG_TTL = 120;    // seconds a failed stop is remembered
const STALE_MAX = 120;  // seconds a stale copy may still be served while it is refreshed

function fail(int $code, string $msg, int $retry = 0): void {
    if (!empty($GLOBALS['bg'])) {
        exit; // background refresh: the response has already been sent
    }
    http_response_code($code);
    header('Content-Type: application/json');
    if ($retry > 0) {
        header('Retry-After: ' . $retry);
    }
    echo '{"error":"' . $msg . '"}';
    exit;
}

// ---------------------------------------------------------------- State (private dir)

// Private state directory (caches, EMT token, counters, markers): outside the webroot
// (domains/<site>/cache/madrid-transit), created 0700; the system temp dir only if that fails.
function state_dir(): string {
    static $dir = null;
    if ($dir === null) {
        $dir = __DIR__ . '/../../cache/madrid-transit';
        if (!is_dir($dir)) {
            @mkdir($dir, 0700, true);
        }
        if (!is_dir($dir) || !is_writable($dir)) {
            $dir = sys_get_temp_dir();
        }
    }
    return $dir;
}

// Upstream timeout in seconds: 8 while a client waits, 12 in a background refresh.
function http_timeout(): int {
    return empty($GLOBALS['bg']) ? 8 : 12;
}

function state_file(string $name): string {
    return state_dir() . '/' . $name;
}

// Atomic write: a temp file in the same directory, then rename.
function state_write(string $path, string $data, int $mode): void {
    $tmp = $path . '.' . getmypid();
    $old = umask(0077);
    $ok = file_put_contents($tmp, $data) !== false;
    umask($old);
    if ($ok && chmod($tmp, $mode)) {
        rename($tmp, $path);
    } else {
        @unlink($tmp);
    }
}

function is_fresh(string $path, int $ttl): bool {
    return is_file($path) && time() - filemtime($path) < $ttl;
}

// Increments the counter file `$name` under an exclusive lock and returns the new value
// (0 if the file cannot be used, so a broken state dir never blocks requests).
function counter_hit(string $name): int {
    $old = umask(0077);
    $fh = @fopen(state_file($name), 'c+');
    umask($old);
    if ($fh === false) {
        return 0;
    }
    $n = 0;
    if (flock($fh, LOCK_EX)) {
        $n = (int) stream_get_contents($fh) + 1;
        rewind($fh);
        ftruncate($fh, 0);
        fwrite($fh, (string) $n);
        fflush($fh);
        flock($fh, LOCK_UN);
    }
    fclose($fh);
    return $n;
}

// Deletes counters and markers older than 10 minutes (called on about 1 in 50 requests).
function cleanup_state(): void {
    $dir = state_dir();
    foreach (@scandir($dir) ?: [] as $n) {
        if (preg_match('/^(ip|budget|neg|lock)-/', $n) === 1 && (int) @filemtime($dir . '/' . $n) < time() - 600) {
            @unlink($dir . '/' . $n);
        }
    }
}

// Per-client limit: 429 above IP_LIMIT requests in the current minute. The counter file is
// named by a hash of IP+minute, so no raw IP is stored.
function rate_limit_ip(): void {
    if (random_int(1, 50) === 1) {
        cleanup_state();
    }
    $key = hash('sha256', ($_SERVER['REMOTE_ADDR'] ?? '') . date('YmdHi'));
    if (counter_hit('ip-' . $key) > IP_LIMIT) {
        fail(429, 'too many requests', 30);
    }
}

// True when the upstream call may go ahead; counts it (per upstream and minute). Call right
// before each upstream request. Going over the limit is remembered for busy().
function budget_ok(string $name, int $limit): bool {
    if (counter_hit('budget-' . $name . '-' . date('YmdHi')) > $limit) {
        $GLOBALS['over_budget'] = true;
        return false;
    }
    return true;
}

function over_budget(): bool {
    return !empty($GLOBALS['over_budget']);
}

// Negative cache: the last failure of a stop as {"c": status, "m": message}, for NEG_TTL s.
function neg_get(string $key): ?array {
    $file = state_file('neg-' . $key);
    $n = is_fresh($file, NEG_TTL) ? json_decode((string) @file_get_contents($file), true) : null;
    if (is_array($n) && is_int($n['c'] ?? null) && $n['c'] >= 400 && $n['c'] < 600
        && is_string($n['m'] ?? null) && preg_match('/^[a-z ]{1,40}\z/', $n['m']) === 1) {
        return $n;
    }
    return null;
}

function neg_set(string $key, int $code, string $msg): void {
    state_write(state_file('neg-' . $key), json_encode(['c' => $code, 'm' => $msg]), 0600);
}

// Reads `stop` from the query, checks its format ($re, else 400) and the generated allow-list
// ($group in rt-stops.php, else 404). Runs before anything contacts an upstream. Without the
// allow-list file only the format is checked.
function check_stop(string $group, string $re): string {
    $stop = $_GET['stop'] ?? '';
    // \z (not $) so a trailing newline cannot slip through.
    if (!is_string($stop) || !preg_match($re, $stop)) {
        fail(400, 'bad stop');
    }
    $allow = is_file(__DIR__ . '/rt-stops.php') ? require __DIR__ . '/rt-stops.php' : null;
    if (is_array($allow) && !isset($allow[$group][$stop])) {
        fail(404, 'unknown stop');
    }
    return $stop;
}

// ---------------------------------------------------------------- EMT Madrid (MobilityLabs)

const EMT_HOST = 'https://openapi.emtmadrid.es/';

// One HTTPS request to the EMT host (cURL when available, else a stream context).
// Returns [http status, body or null]; any other host is refused, and so is a call over the
// per-minute EMT budget (counted here, right before the request).
function emt_http(string $method, string $url, array $headers, ?string $body = null): array {
    if (strpos($url, EMT_HOST) !== 0 || !budget_ok('emt', EMT_BUDGET)) {
        return [0, null];
    }
    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => http_timeout(),
            CURLOPT_CONNECTTIMEOUT => 5,
            CURLOPT_FOLLOWLOCATION => false,
            CURLOPT_PROTOCOLS => CURLPROTO_HTTPS,
            CURLOPT_CUSTOMREQUEST => $method,
            CURLOPT_HTTPHEADER => $headers,
        ]);
        if ($body !== null) {
            curl_setopt($ch, CURLOPT_POSTFIELDS, $body);
        }
        $out = curl_exec($ch);
        $status = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);
        return [$status, is_string($out) ? $out : null];
    }
    $http = ['method' => $method, 'timeout' => http_timeout(), 'ignore_errors' => true, 'follow_location' => 0,
        'header' => implode("\r\n", $headers) . "\r\n"];
    if ($body !== null) {
        $http['content'] = $body;
    }
    $out = @file_get_contents($url, false, stream_context_create(['http' => $http]));
    $status = 0;
    if (isset($http_response_header[0]) && preg_match('#^HTTP/\S+ (\d{3})#', $http_response_header[0], $m)) {
        $status = (int) $m[1];
    }
    return [$status, is_string($out) ? $out : null];
}

// A header value must be printable ASCII (space included, for passwords) with no CR/LF,
// control or non-ASCII characters, so it cannot inject headers.
function emt_clean($v): bool {
    return is_string($v) && preg_match('/^[\x20-\x7e]{1,2048}\z/', $v) === 1;
}

// {"email":…,"password":…} and/or {"clientId":…,"passKey":…} from the config file outside the
// webroot. Only complete, valid pairs are returned; a present but invalid pair (for example a
// non-ASCII password) with no valid one is 'emt config invalid'.
function emt_config(): array {
    $raw = @file_get_contents(__DIR__ . '/../../emt.json');
    $cfg = is_string($raw) ? json_decode($raw, true) : null;
    if (!is_array($cfg)) {
        fail(503, 'emt not configured');
    }
    $out = [];
    $invalid = false;
    foreach ([['email', 'password'], ['clientId', 'passKey']] as [$a, $b]) {
        $x = $cfg[$a] ?? null;
        $y = $cfg[$b] ?? null;
        if ($x === null && $y === null) {
            continue;
        }
        if (emt_clean($x) && emt_clean($y)) {
            $out[$a] = $x;
            $out[$b] = $y;
        } else {
            $invalid = true;
        }
    }
    if ($out === []) {
        fail(503, $invalid ? 'emt config invalid' : 'emt not configured');
    }
    return $out;
}

// Seconds-to-live of a fresh login: tokenSecExpiration (the API extends it on each call).
function emt_ttl(array $d): int {
    if (isset($d['tokenSecExpiration']) && is_numeric($d['tokenSecExpiration'])) {
        return (int) $d['tokenSecExpiration'];
    }
    return 3600; // absent: documented sessions last far longer
}

// Logs in and caches the token (file mode 600 in the state dir); null on failure. Prefers
// email/password headers, else X-ClientId/passKey (legacy). Wrong user or password ("92"/"89")
// ends the request with 502 instead of retrying.
function emt_login(array $cfg, string $tokenFile): ?string {
    if (isset($cfg['email'], $cfg['password'])) {
        $auth = ['email: ' . $cfg['email'], 'password: ' . $cfg['password']];
    } else {
        $auth = ['X-ClientId: ' . $cfg['clientId'], 'passKey: ' . $cfg['passKey']];
    }
    [$status, $body] = emt_http('GET', EMT_HOST . 'v1/mobilitylabs/user/login/', array_merge($auth, ['Accept: application/json']));
    $j = $body !== null ? json_decode($body, true) : null;
    $code = is_array($j) ? ($j['code'] ?? '') : '';
    if (in_array($code, ['92', '89'], true)) {
        fail(502, 'emt login failed');
    }
    $d = $j['data'][0] ?? null;
    if ($status !== 200 || !in_array($code, ['00', '01'], true) || !is_array($d) || !emt_clean($d['accessToken'] ?? null)) {
        return null;
    }
    $exp = time() + emt_ttl($d);
    state_write($tokenFile, json_encode(['token' => $d['accessToken'], 'exp' => $exp]), 0600);
    return $d['accessToken'];
}

// Cached token while it has more than 60 s left, else a new login.
function emt_token(array $cfg, bool $force): ?string {
    $tokenFile = state_file('emt-token.json');
    $c = $force || !is_file($tokenFile) ? null : json_decode((string) @file_get_contents($tokenFile), true);
    if (is_array($c) && emt_clean($c['token'] ?? null) && ($c['exp'] ?? 0) - 60 > time()) {
        return $c['token'];
    }
    return emt_login($cfg, $tokenFile);
}

// Arrivals for a stop: [decoded JSON or null, raw body]. Null decoded = transport or HTTP failure.
function emt_arrivals(string $stop, string $token): array {
    [$status, $body] = emt_http(
        'POST',
        EMT_HOST . 'v2/transport/busemtmad/stops/' . $stop . '/arrives/',
        ['accessToken: ' . $token, 'Content-Type: application/json', 'Accept: application/json'],
        json_encode([
            'cultureInfo' => 'ES',
            'Text_StopRequired_YN' => 'N',
            'Text_EstimationsRequired_YN' => 'Y',
            'Text_IncidencesRequired_YN' => 'Y',
            'DateTime_Referenced_Incidencies_YYYYMMDD' => (new DateTime('now', new DateTimeZone('Europe/Madrid')))->format('Ymd'),
        ])
    );
    $j = $status === 200 && $body !== null ? json_decode($body, true) : null;
    return [is_array($j) ? $j : null, $body];
}

// Fetches the arrivals of one stop into $cache (30 s). Re-logs in once on a token error. Failures
// are remembered (negative cache); a stale cache is kept as the answer where there is one.
function emt_fetch(string $stop, string $cache): void {
    $cfg = emt_config();
    $code = null;
    $body = null;
    foreach ([false, true] as $force) {
        $token = emt_token($cfg, $force);
        if ($token === null) {
            if (over_budget()) {
                break;
            }
            continue;
        }
        [$j, $body] = emt_arrivals($stop, $token);
        $code = $j['code'] ?? null;
        if ($code === '00' || $code === '98' || over_budget()) {
            break; // "98": API limit, a new login would not help
        }
    }
    if ($code === '00') {
        state_write($cache, (string) $body, 0600);
    } elseif (over_budget()) {
        if (!is_file($cache)) {
            fail(503, 'busy', 30);
        }
    } elseif ($code === '98') {
        neg_set('emt-' . $stop, 429, 'emt limit exceeded');
        fail(429, 'emt limit exceeded');
    } elseif ($code === '80') {
        neg_set('emt-' . $stop, 404, 'emt stop not found');
        fail(404, 'emt stop not found');
    } else {
        neg_set('emt-' . $stop, 502, 'upstream unavailable');
        if (!is_file($cache)) {
            fail(502, 'upstream unavailable');
        }
    }
}

// A stop's arrivals are refreshed when missing or stale (see serve_swr); the failure paths
// above are shared by the synchronous and the background run.
function emt_refresh(string $stop, string $cache): void {
    $neg = neg_get('emt-' . $stop);
    if ($neg === null) {
        emt_fetch($stop, $cache);
    } elseif ($neg['c'] !== 502 || !is_file($cache)) {
        fail($neg['c'], $neg['m']); // a recent failure: no upstream call
    }
}

// Generic upstream (Renfe, CRTM): one fetch into $cache. Only something that decodes as JSON is
// cached (CRTM answers errors with HTML or text). Failures are remembered when $neg is set; a
// stale cache stays the answer where there is one.
function generic_refresh(string $url, string $cache, ?string $neg, ?string $budget): void {
    $stale = is_file($cache);
    if ($neg !== null && neg_get($neg) !== null) {
        // Failed recently: no upstream call.
        if (!$stale) {
            fail(502, 'upstream unavailable');
        }
    } elseif ($budget !== null && !budget_ok($budget, CRTM_BUDGET)) {
        if (!$stale) {
            fail(503, 'busy', 30);
        }
    } else {
        $ctx = stream_context_create(['http' => ['timeout' => http_timeout(), 'header' => "Accept: application/json\r\n"]]);
        $body = @file_get_contents($url, false, $ctx);
        if ($body !== false && $body !== '' && json_decode($body) !== null) {
            state_write($cache, $body, 0600);
        } else {
            if ($neg !== null) {
                neg_set($neg, 502, 'upstream unavailable');
            }
            if (!$stale) {
                fail(502, 'upstream unavailable');
            }
        }
    }
}

// Stale-while-revalidate. Upstreams answer erratically (0.4-8 s), so nobody should wait for
// them when a usable copy exists:
//   - younger than $ttl: served as is;
//   - $ttl..STALE_MAX s old: served at once, then refreshed after the response is flushed
//     (needs fastcgi_finish_request; one refresher per stop via a lock file, others skip);
//     without fastcgi_finish_request, or with no or an older copy, the fetch is synchronous.
// Every answer carries X-Data-Age (seconds since the copy was fetched; 0 after a fresh fetch).
function serve_swr(string $cache, int $ttl, callable $refresh): void {
    $age = is_file($cache) ? max(0, time() - (int) filemtime($cache)) : null;
    $bg = $age !== null && $age >= $ttl && $age < STALE_MAX && function_exists('fastcgi_finish_request');
    if ($age === null || ($age >= $ttl && !$bg)) {
        $refresh();
        clearstatcache(true, $cache);
        $age = is_file($cache) ? max(0, time() - (int) filemtime($cache)) : 0;
    }
    header('Content-Type: application/json');
    header('X-Data-Age: ' . $age);
    // Only a copy still fresh may be held by the browser, and only for its remaining life.
    header('Cache-Control: ' . ($age < $ttl ? 'public, max-age=' . ($ttl - $age) : 'no-store'));
    readfile($cache);
    if (!$bg) {
        exit;
    }
    ignore_user_abort(true);
    fastcgi_finish_request();
    // From here nobody waits: longer upstream timeout, and fail() just ends the script.
    $GLOBALS['bg'] = true;
    @set_time_limit(30);
    $lock = @fopen(state_file('lock-' . basename($cache)), 'c');
    if ($lock !== false && flock($lock, LOCK_EX | LOCK_NB)) {
        $refresh();
        flock($lock, LOCK_UN);
    }
    exit;
}

$f = $_GET['f'] ?? '';
if (!is_string($f)) {
    fail(400, 'bad feed');
}

if ($f === 'emt') {
    $stop = check_stop('emt', '/^\d{1,6}\z/');
    $cache = state_file('emt-' . $stop . '.json');
    $ttl = 30;
    $refresh = function () use ($stop, $cache): void {
        emt_refresh($stop, $cache);
    };
} elseif ($f === 'crtm' || in_array($f, ['trip_updates', 'trip_updates_LD', 'alerts'], true)) {
    if ($f === 'crtm') {
        $stop = check_stop('crtm', '/^(4|6|8|10)_\d{1,6}\z/');
        $url = 'https://www.crtm.es/widgets/api/GetStopsTimes.php?codStop=' . $stop . '&type=1&orderBy=2&stopTimesByIti=3';
        $cache = state_file('crtm-' . $stop . '.json');
        $ttl = 30;
        $neg = 'crtm-' . $stop;
        $budget = 'crtm';
    } else {
        $url = 'https://gtfsrt.renfe.com/' . $f . '.json';
        $cache = state_file('renfe-' . $f . '.json');
        $ttl = 15;
        $neg = null;
        $budget = null;
    }
    $refresh = function () use ($url, $cache, $neg, $budget): void {
        generic_refresh($url, $cache, $neg, $budget);
    };
} else {
    fail(400, 'bad feed');
}

rate_limit_ip();
serve_swr($cache, $ttl, $refresh);
